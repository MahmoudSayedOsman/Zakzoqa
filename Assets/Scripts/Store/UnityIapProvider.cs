// The real store: Google Play through Unity IAP 5. Compiles only when the package is installed
// (UNITY_PURCHASING comes from a versionDefine on com.unity.purchasing in Zakzoqa.Runtime), so
// the project still builds without it; IapManager falls back to the stand-in in that case.
// (From Shadow Escape, unchanged in behaviour.)
#if UNITY_PURCHASING
using System;
using System.Collections.Generic;
using UnityEngine;
using UnityEngine.Purchasing;
using UnityEngine.Purchasing.Security;

namespace Zakzoqa
{

    // Written against Unity IAP 5.4 — the StoreController API. Version 4's IStoreListener and
    // UnityPurchasing.Initialize, which most examples still show, do not exist here.
    //
    // NO UNITY GAMING SERVICES. UnityServices.InitializeAsync is deliberately never called: in IAP 5 it
    // is optional, and all it adds is sending every purchase to Unity Analytics. The privacy policy says
    // the game runs no analytics of its own, and this keeps that true. (The analytics code in the
    // package is also compiled out unless com.unity.services.analytics is installed, which it is not.)
    //
    // HOW A PURCHASE FLOWS:
    //   Purchase  -> PurchaseProduct -> OnPurchasePending -> grant, then ConfirmPurchase
    //                                   OnPurchaseFailed  -> Cancelled / AlreadyOwned / Failed
    //                                   OnPurchaseDeferred -> Deferred (a cash payment still to clear)
    // Granting BEFORE confirming is what the package's own sample does and what matters: if the app dies
    // between the two, the store re-delivers the pending order on the next launch, and granting a
    // non-consumable twice is harmless. Confirming first would risk a player who paid and got nothing.
    //
    // OWNERSHIP ARRIVES ON ITS OWN, TOO. After connecting, FetchPurchases reports what this account
    // already owns, and pending orders (a deferred payment that cleared while the app was closed) come
    // through OnPurchasePending by default. Both raise OwnershipFound, so a reinstall gets Remove Ads back
    // without the player pressing anything. The fetch is also the store's COMPLETE list, and raises
    // OwnershipRefreshed: IapManager takes back whatever it does not include.
    //
    // EVERY RECEIPT IS CHECKED. Google signs each purchase with the app's own key; a patched billing
    // library on a rooted phone can report a purchase that never happened, but cannot sign it. Receipts
    // are checked against the license key in GooglePlayTangle — generated by Unity IAP's Receipt
    // Validation Obfuscator from the key in Play Console > Monetization setup. Until that class exists
    // the check is off (logged once), because refusing every purchase would be worse than trusting them.
    // A receipt that fails is not granted and not confirmed: Google refunds an unconfirmed purchase
    // after three days, so if the check is ever wrong the player gets their money back.
    public class UnityIapProvider : IPurchaseProvider
    {
        readonly StoreController store;
        readonly List<ProductDefinition> definitions = new List<ProductDefinition>();
        readonly HashSet<string> owned = new HashSet<string>();
        readonly Dictionary<string, Action<PurchaseResult>> waiting = new Dictionary<string, Action<PurchaseResult>>();
        bool connected, connecting;

        CrossPlatformValidator validator;
        bool validatorLooked;

        public event Action<string> OwnershipFound;
        public event Action OwnershipRefreshed;
        public event Action<string> ConsumableDelivered;

        // The coin packs. They are never "owned": confirming one consumes it, and
        // what it paid is coins, handed over at the moment of purchase (IapManager.Grant).
        readonly HashSet<string> consumables = new HashSet<string>();

        public UnityIapProvider(IEnumerable<IapProductDef> catalog)
        {
            foreach (IapProductDef def in catalog)
            {
                if (def == null || string.IsNullOrEmpty(def.productId)) continue;
                ProductType type = def.kind == IapProductKind.NonConsumable ? ProductType.NonConsumable : ProductType.Consumable;
                definitions.Add(new ProductDefinition(def.productId, type));
                if (type == ProductType.Consumable) consumables.Add(def.productId);
            }

            store = UnityIAPServices.StoreController();
            store.OnPurchasePending += OnPurchasePending;
            store.OnPurchaseConfirmed += OnPurchaseConfirmed;
            store.OnPurchaseFailed += OnPurchaseFailed;
            store.OnPurchaseDeferred += OnPurchaseDeferred;
            store.OnPurchasesFetched += OnPurchasesFetched;
            store.OnPurchasesFetchFailed += failure => Debug.LogWarning($"[IAP] could not read what this account owns: {failure.Message}");
            store.OnProductsFetched += _ => store.FetchPurchases();
            store.OnProductsFetchFailed += failure => Debug.LogWarning($"[IAP] could not read the products: {failure.FailureReason}");
            store.OnStoreDisconnected += failure =>
            {
                connected = false;
                Debug.LogWarning($"[IAP] store disconnected: {failure.Message}");
            };

            Connect();
        }

        // Connects, then asks for the products; their arrival asks for this account's purchases.
        async void Connect()
        {
            if (connected || connecting) return;
            connecting = true;
            try
            {
                await store.Connect();
                connected = true;
                store.FetchProducts(definitions);
            }
            catch (Exception e)
            {
                Debug.LogWarning($"[IAP] could not connect to the store: {e.Message}");
            }
            finally
            {
                connecting = false;
            }
        }

        public void Purchase(string productId, Action<PurchaseResult> onComplete)
        {
            if (!connected)
            {
                // Try again for next time, and say no now rather than leaving the button hanging.
                Connect();
                onComplete?.Invoke(PurchaseResult.Failed);
                return;
            }

            Product product = store.GetProductById(productId);
            if (product == null || !product.availableToPurchase)
            {
                Debug.LogWarning($"[IAP] '{productId}' is not available from the store — is it active in the Play Console?");
                onComplete?.Invoke(PurchaseResult.Failed);
                return;
            }

            waiting[productId] = onComplete;
            store.PurchaseProduct(product);
        }

        public void Restore(Action<bool> onComplete)
        {
            if (!connected)
            {
                Connect();
                onComplete?.Invoke(false);
                return;
            }

            // Re-read what the account owns as well: on Google Play that is what a restore really is.
            store.FetchPurchases();
            store.RestoreTransactions((success, error) =>
            {
                if (!success) Debug.LogWarning($"[IAP] restore failed: {error}");
                onComplete?.Invoke(success);
            });
        }

        public string GetLocalizedPrice(string productId)
        {
            if (!connected) return null;
            Product product = store.GetProductById(productId);
            return product != null && product.metadata != null ? product.metadata.localizedPriceString : null;
        }

        public bool Owns(string productId) => owned.Contains(productId);

        // Paid for. Record it, hand it to whoever asked (or announce it, for a purchase nobody is
        // waiting on), then confirm to the store.
        void OnPurchasePending(PendingOrder order)
        {
            bool allGenuine = true;
            foreach (CartItem item in order.CartOrdered.Items())
            {
                string id = item.Product.definition.id;
                if (!IsGenuine(order, id)) { allGenuine = false; Resolve(id, PurchaseResult.Failed); continue; }

                if (consumables.Contains(id)) PayConsumable(order, id);
                else MarkOwned(id, PurchaseResult.Success);
            }
            if (allGenuine) store.ConfirmPurchase(order);
        }

        // A coin pack is paid ONCE PER ORDER, however many times the store delivers it. An order whose
        // confirmation failed comes back at every launch until it is confirmed, and each delivery would
        // otherwise pay its coins again — so each paid order's transaction id is remembered.
        void PayConsumable(Order order, string id)
        {
            string tx = order.Info != null ? order.Info.TransactionID : null;
            if (PaidOrders.Contains(tx))
            {
                // Already paid: tell a waiting flow it owns it (no coins), and confirm again below.
                Resolve(id, PurchaseResult.AlreadyOwned);
                return;
            }

            PaidOrders.Add(tx);
            if (!Resolve(id, PurchaseResult.Success)) ConsumableDelivered?.Invoke(id);
        }

        // The transaction ids of consumable orders already paid for, newest last, kept to the last 100.
        // Under the Ent_ prefix: guarded by SaveGuard like the entitlements, and never sent to the cloud.
        static class PaidOrders
        {
            const string Key = SaveKeys.EntitlementPrefix + "PaidOrders";
            const int Keep = 100;

            public static bool Contains(string tx) =>
                !string.IsNullOrEmpty(tx) && Array.IndexOf(Prefs.GetString(Key, "").Split('|'), tx) >= 0;

            public static void Add(string tx)
            {
                if (string.IsNullOrEmpty(tx)) return;
                List<string> list = new List<string>(Prefs.GetString(Key, "").Split(new[] { '|' }, StringSplitOptions.RemoveEmptyEntries));
                list.Add(tx);
                if (list.Count > Keep) list.RemoveRange(0, list.Count - Keep);
                Prefs.SetString(Key, string.Join("|", list));
                Prefs.Save();
            }
        }

        // The store's answer to the confirmation. A confirmation that failed is logged; the entitlement
        // was already granted, and the store will re-deliver the order until it is confirmed.
        void OnPurchaseConfirmed(Order order)
        {
            if (order is FailedOrder failed)
                Debug.LogWarning($"[IAP] confirming the purchase failed: {failed.FailureReason} {failed.Details}");
        }

        void OnPurchaseFailed(FailedOrder order)
        {
            PurchaseResult result;
            switch (order.FailureReason)
            {
                case PurchaseFailureReason.UserCancelled: result = PurchaseResult.Cancelled; break;
                // Google answers "already owned" as a duplicate: the player bought it on another
                // install. That is ownership, not a failure.
                case PurchaseFailureReason.DuplicateTransaction: result = PurchaseResult.AlreadyOwned; break;
                default: result = PurchaseResult.Failed; break;
            }

            foreach (CartItem item in order.CartOrdered.Items())
            {
                string id = item.Product.definition.id;
                if (result == PurchaseResult.AlreadyOwned && !consumables.Contains(id)) owned.Add(id);
                Resolve(id, result);
            }
            if (result == PurchaseResult.Failed)
                Debug.LogWarning($"[IAP] purchase failed: {order.FailureReason} {order.Details}");
        }

        // A payment that has not cleared yet (cash, some carriers). The purchase is not complete; it
        // arrives later as a pending order, possibly after the app has closed.
        void OnPurchaseDeferred(DeferredOrder order)
        {
            foreach (CartItem item in order.CartOrdered.Items())
                Resolve(item.Product.definition.id, PurchaseResult.Deferred);
        }

        // Everything this account owns, read after connecting and on a restore. Paid-for orders still
        // waiting for confirmation count; deferred ones (not paid yet) do not.
        void OnPurchasesFetched(Orders orders)
        {
            HashSet<string> listed = new HashSet<string>();
            if (orders.ConfirmedOrders != null)
                foreach (ConfirmedOrder order in orders.ConfirmedOrders) AddGenuine(order, listed);
            if (orders.PendingOrders != null)
                foreach (PendingOrder order in orders.PendingOrders) AddGenuine(order, listed);

            owned.Clear();
            foreach (string id in listed) MarkOwned(id, PurchaseResult.Success);
            OwnershipRefreshed?.Invoke();
        }

        void AddGenuine(Order order, HashSet<string> into)
        {
            foreach (CartItem item in order.CartOrdered.Items())
            {
                string id = item.Product.definition.id;
                // Consumables are never owned; an unconfirmed one is paid through OnPurchasePending.
                if (consumables.Contains(id)) continue;
                if (IsGenuine(order, id)) into.Add(id);
            }
        }

        // Whether Google signed this order's receipt, for this app and this product.
        bool IsGenuine(Order order, string productId)
        {
            CrossPlatformValidator v = Validator();
            if (v == null) return true;

            try
            {
                foreach (IPurchaseReceipt receipt in v.Validate(order.Info.Receipt))
                    if (receipt != null && receipt.productID == productId) return true;
                Debug.LogWarning($"[IAP] a receipt for '{productId}' was signed, but for a different product; refused.");
                return false;
            }
            catch (IAPSecurityException e)
            {
                Debug.LogWarning($"[IAP] a receipt for '{productId}' failed validation and was refused: {e.GetType().Name} {e.Message}");
                return false;
            }
            catch (Exception e)
            {
                Debug.LogWarning($"[IAP] a receipt for '{productId}' could not be read and was refused: {e.Message}");
                return false;
            }
        }

        // Built from GooglePlayTangle when the project has one with the license key in it. Found by
        // name, so the game compiles before the class is generated; null means the check is off.
        CrossPlatformValidator Validator()
        {
            if (validatorLooked) return validator;
            validatorLooked = true;

            Type tangle = null;
            foreach (System.Reflection.Assembly asm in AppDomain.CurrentDomain.GetAssemblies())
            {
                tangle = asm.GetType("UnityEngine.Purchasing.Security.GooglePlayTangle", false);
                if (tangle != null) break;
            }

            byte[] key = null;
            if (tangle != null)
            {
                System.Reflection.FieldInfo populated = tangle.GetField("IsPopulated");
                System.Reflection.MethodInfo data = tangle.GetMethod("Data", Type.EmptyTypes);
                bool isPopulated = populated == null || (bool)populated.GetValue(null);
                if (isPopulated && data != null) key = data.Invoke(null, null) as byte[];
            }

            if (key == null || key.Length == 0)
            {
                Debug.LogWarning("[IAP] receipt validation is OFF: GooglePlayTangle is missing or empty. Generate it in "
                    + "Unity: Services > In-App Purchasing > Receipt Obfuscator, with Zakzoqa's license key from the Play Console.");
                return null;
            }

            try
            {
                validator = new CrossPlatformValidator(key, Application.identifier);
            }
            catch (Exception e)
            {
                Debug.LogWarning($"[IAP] receipt validation is OFF: the validator could not be built: {e.Message}");
            }
            return validator;
        }

        void MarkOwned(string productId, PurchaseResult resultForWaiter)
        {
            owned.Add(productId);
            if (!Resolve(productId, resultForWaiter)) OwnershipFound?.Invoke(productId);
        }

        // Answers the purchase flow waiting on this product, if one is. Returns whether one was.
        bool Resolve(string productId, PurchaseResult result)
        {
            if (!waiting.TryGetValue(productId, out Action<PurchaseResult> onComplete)) return false;
            waiting.Remove(productId);
            onComplete?.Invoke(result);
            return true;
        }
    }
}
#endif
